const norm = (s) => (s || "").toLowerCase().replace(/^\s*\d+\s*[.:)-]\s*/, "").replace(/[^a-z0-9 ]+/g, " ").replace(/\s+/g, " ").trim();
const tokens = (s) => new Set(norm(s).split(" ").filter((w) => w.length > 2));

export const chaptersFor = (subject) =>
  SYLLABUS.filter((c) => c.subject.toLowerCase() === (subject || "").trim().toLowerCase());

// Best syllabus chapter for a page's chapter name (same subject only). Returns row or null.
export function matchChapter(subject, chapterName) {
  const list = chaptersFor(subject);
  const n = norm(chapterName);
  const exact = list.find((c) => norm(c.name) === n);
  if (exact) return exact;
  const a = tokens(chapterName);
  let best = null, bestScore = 0;
  for (const c of list) {
    const b = tokens(c.name);
    const inter = [...a].filter((w) => b.has(w)).length;
    const score = inter / Math.max(1, new Set([...a, ...b]).size);
    if (score > bestScore) { best = c; bestScore = score; }
  }
  return bestScore >= 0.5 ? best : null;
}
